namespace WindowsShell.Audio;

// Интерфейсы Core Audio. Порядок методов = порядок в таблице COM, поэтому неиспользуемые
// методы тоже объявлены (как места). Имена — как в документации Windows.

public enum EDataFlow { Render = 0, Capture = 1 }
public enum ERole { Console = 0, Multimedia = 1, Communications = 2 }

[ComImport, Guid("BCDE0395-E52F-467C-8E3D-C4579291692E")]
